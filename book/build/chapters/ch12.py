def _blank_rows(cols, n, first_labels=None):
    rows = []
    for i in range(n):
        row = []
        for c in range(cols):
            if first_labels and c == 0:
                row.append(first_labels[i] if i < len(first_labels) else "")
            else:
                row.append(("", "blank"))
        rows.append(row)
    return rows

